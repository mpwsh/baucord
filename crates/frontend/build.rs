//! Generates `fill_tr_from_ftl` (included by `app.rs`): one setter per
//! `Tr` property, each from the Fluent message of the same name.
//!
//! `crates/ui/slint/tr.slint` declares the properties (Slint has to
//! know them) and `crates/i18n/locales/*.ftl` hold the words, English
//! included. Nothing is written twice, so nothing can drift: a new
//! string is a line in tr.slint and a message in each .ftl, and the
//! build stops here when a locale lacks one.

use std::{collections::HashSet, env, fmt::Write as _, fs, path::PathBuf};

/// `Tr` properties `fill_tr` sets by hand, from per-platform messages
/// (`audio-output-hint-android`): there is no message of their name.
const BY_HAND: &[&str] = &["audio-output-hint"];

fn main() {
    let here = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("set by cargo"));
    let tr_path = here.join("../ui/slint/tr.slint");
    let locales = here.join("../i18n/locales");
    println!("cargo:rerun-if-changed={}", tr_path.display());
    println!("cargo:rerun-if-changed={}", locales.display());

    let tr = fs::read_to_string(&tr_path).expect("read tr.slint");
    let mut names = Vec::new();
    for line in tr.lines() {
        let Some(rest) = line.trim().strip_prefix("in property <string> ") else {
            continue;
        };
        let name = rest.trim_end_matches(';').trim();
        assert!(
            !name.contains(':'),
            "tr.slint: `{line}` has a value; the words go in the .ftl files"
        );
        names.push(name.to_string());
    }
    assert!(!names.is_empty(), "tr.slint declares no strings");

    let mut missing = Vec::new();
    let mut files: Vec<PathBuf> = fs::read_dir(&locales)
        .expect("read the locales")
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|x| x == "ftl"))
        .collect();
    files.sort();
    for file in &files {
        let ftl = fs::read_to_string(file).expect("read an .ftl");
        let ids: HashSet<&str> = ftl
            .lines()
            .filter(|l| l.starts_with(|c: char| c.is_ascii_lowercase()))
            .filter_map(|l| l.split_once('=').map(|(id, _)| id.trim()))
            .collect();
        for name in &names {
            if !BY_HAND.contains(&name.as_str()) && !ids.contains(name.as_str()) {
                let locale = file.file_name().unwrap_or_default().to_string_lossy();
                missing.push(format!("{locale}: {name}"));
            }
        }
    }
    assert!(
        missing.is_empty(),
        "tr.slint strings with no message in a locale:\n  {}",
        missing.join("\n  ")
    );

    let mut out = String::from(
        "// Generated by build.rs from tr.slint: every `Tr` property from the\n\
         // Fluent message of the same name.\n\
         #[allow(clippy::too_many_lines)]\n\
         fn fill_tr_from_ftl(tr: &Tr) {\n",
    );
    for name in names.iter().filter(|n| !BY_HAND.contains(&n.as_str())) {
        let setter = name.replace('-', "_");
        writeln!(out, "    tr.set_{setter}(t!(\"{name}\").into());").expect("a String");
    }
    out.push_str("}\n");
    let dest = PathBuf::from(env::var("OUT_DIR").expect("set by cargo")).join("fill_tr.rs");
    fs::write(dest, out).expect("write fill_tr.rs");
}
