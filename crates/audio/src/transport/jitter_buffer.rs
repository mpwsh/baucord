//! Adaptive jitter buffer with per-peer sequence tracking and mixing.
//!
//! Buffers decoded audio per-peer, mixes to mono, and adapts its target
//! depth based on inter-arrival jitter estimation and buffer health feedback.
//!
//! ## v0.6 changes from v0.5
//!
//! - **Arrival-time jitter estimation**: Jitter is now measured from timestamps
//!   stamped at network receive time (before decode), not inter-arrival of
//!   decoded frames. This eliminates thread-scheduling noise from the estimate.
//! - **Severity-scaled adaptation**: Buffer target increases proportionally to
//!   the number of late/gap events per cycle, not a flat +10ms regardless.
//!   A burst of 5 gaps bumps harder than a single late packet.
//! - **Burst-safe drain**: Excess audio after a burst arrival is only discarded
//!   after sustained excess for multiple ticks, preventing audio drops right
//!   after network recovery.
//! - **Longer stability window**: Requires 200 stable ticks (2s) before draining,
//!   with a slower drain rate (0.2ms/tick). Prevents the drain→spike→underrun
//!   oscillation on bursty WiFi/cellular networks.
//! - **Still mixes whatever is available** (no hard gate on target depth).

use crate::config::PeerAudioSettings;
use crate::processor::limiter::Limiter;
use crate::FRAME_SIZE;
use std::collections::{HashMap, VecDeque};
use std::sync::{Arc, Mutex};
use std::time::Instant;

/// Decoded audio with metadata that survives the decoder→output channel.
///
/// The `arrival_time` is stamped when the packet enters the decoder pool
/// (at network receive), NOT when decoding finishes. This gives the jitter
/// buffer clean network timing uncontaminated by thread scheduling.
#[derive(Debug, Clone)]
pub struct DecodedFrame {
    pub peer_id: u64,
    pub seq: u32,
    pub arrival_time: Instant,
    pub samples: Vec<f32>,
    /// True if this frame was generated by PLC/FEC (not a real packet).
    /// Concealment frames don't carry valid arrival times and should not
    /// be used for jitter estimation.
    pub is_concealment: bool,
}

/// Per-peer state inside the jitter buffer.
struct PeerBuffer {
    /// Audio sample FIFO (decoded f32 at 48 kHz).
    samples: VecDeque<f32>,
    /// Last sequence number we accepted (for gap detection).
    last_seq: Option<u32>,
    /// Arrival time of the last real (non-concealment) packet.
    last_arrival: Option<Instant>,
    /// Smoothed jitter estimate in seconds (exponential moving average).
    /// Uses asymmetric coefficients: fast attack, slower release.
    jitter_estimate: f32,
    /// How many consecutive ticks this peer has had excess samples.
    /// Used to avoid draining burst arrivals prematurely.
    excess_ticks: u32,
    /// Per-peer output limiter — protects listeners from loud transients.
    limiter: Limiter,
}

impl PeerBuffer {
    fn new() -> Self {
        Self {
            samples: VecDeque::with_capacity(4800), // 100ms at 48kHz
            last_seq: None,
            last_arrival: None,
            jitter_estimate: 0.002, // start at 2ms — optimistic, will rise if needed
            excess_ticks: 0,
            limiter: Limiter::new(),
        }
    }
}

pub struct AdaptiveJitterBuffer {
    sample_rate: usize,
    target_samples: usize,
    min_samples: usize,
    max_samples: usize,

    buffers: HashMap<u64, PeerBuffer>,
    peer_settings: Arc<Mutex<HashMap<u64, PeerAudioSettings>>>,

    // ── Adaptation state ────────────────────────────────────────────
    /// Counts adapt() calls since the last late/gap event.
    /// When this is high, conditions are stable and we can drain.
    stable_ticks: u32,
    /// Number of late packets since last adapt() call.
    late_count: u32,
    /// Number of gap events since last adapt() call.
    gap_count: u32,
}

impl AdaptiveJitterBuffer {
    pub fn new(
        sample_rate: usize,
        initial_target_ms: usize,
        peer_settings: Arc<Mutex<HashMap<u64, PeerAudioSettings>>>,
    ) -> Self {
        Self {
            sample_rate,
            target_samples: (initial_target_ms * sample_rate) / 1000,
            min_samples: (2 * sample_rate) / 1000, // 2ms floor
            max_samples: (200 * sample_rate) / 1000, // 200ms ceiling (was 120ms)
            buffers: HashMap::new(),
            peer_settings,
            stable_ticks: 0,
            late_count: 0,
            gap_count: 0,
        }
    }

    /// Ingest a decoded frame with network-stamped arrival time.
    ///
    /// This is the primary entry point from the output worker. It:
    /// 1. Updates jitter estimation from arrival timestamps (real packets only)
    /// 2. Tracks sequence numbers for gap/late detection
    /// 3. Pushes audio samples into the per-peer FIFO
    ///
    /// Unlike v0.5 where `check_packet` and `push_decoded_audio` were separate
    /// calls straddling the decode step, this receives already-decoded audio
    /// with metadata attached. The jitter estimate uses `arrival_time` which
    /// was stamped before decoding, so it's clean network timing.
    pub fn push_frame(&mut self, frame: DecodedFrame) {
        // Check mute
        {
            let Ok(settings) = self.peer_settings.lock() else {
                return;
            };
            if let Some(s) = settings.get(&frame.peer_id) {
                if s.is_muted {
                    // Clear any buffered audio for this peer
                    if let Some(peer) = self.buffers.get_mut(&frame.peer_id) {
                        peer.samples.clear();
                    }
                    return;
                }
            }
        }

        let peer = self
            .buffers
            .entry(frame.peer_id)
            .or_insert_with(PeerBuffer::new);

        // ── Jitter estimation (real packets only) ────────────────────
        // Concealment frames (PLC/FEC) don't have meaningful arrival times
        // and would pollute the jitter estimate.
        if !frame.is_concealment {
            if let Some(last_arrival) = peer.last_arrival {
                let arrival_delta = frame
                    .arrival_time
                    .duration_since(last_arrival)
                    .as_secs_f32();
                let expected_delta = FRAME_SIZE as f32 / self.sample_rate as f32;
                let jitter_sample = (arrival_delta - expected_delta).abs();

                // Asymmetric EMA:
                // - Rising (spike): fast attack, coeff 0.3 → reach ~80% in 3 packets
                // - Falling (stable): slow release, coeff 0.02 → decay over ~50 packets (500ms)
                //   (was 0.03 in v0.5 — slightly slower to prevent premature drain)
                let coeff = if jitter_sample > peer.jitter_estimate {
                    0.3
                } else {
                    0.02
                };
                peer.jitter_estimate = peer.jitter_estimate * (1.0 - coeff) + jitter_sample * coeff;
            }
            peer.last_arrival = Some(frame.arrival_time);
        }

        // ── Sequence tracking ────────────────────────────────────────
        if !frame.is_concealment {
            if let Some(last) = peer.last_seq {
                let expected = last.wrapping_add(1);
                let forward = frame.seq.wrapping_sub(expected);
                let backward = expected.wrapping_sub(frame.seq);

                if backward > 0 && backward <= 10 {
                    // Late packet — we've already moved past this seq
                    self.late_count += 1;
                    // Still push the audio — the mixer will use it if it can.
                    // In v0.5 these were dropped entirely, losing recoverable audio.
                } else if forward > 0 && forward <= 20 {
                    // Gap detected (already handled by decoder with PLC/FEC,
                    // but we track it for adaptation)
                    self.gap_count += 1;
                    peer.last_seq = Some(frame.seq);
                } else if forward > 20 {
                    // Huge jump — reset this peer
                    peer.samples.clear();
                    peer.jitter_estimate = 0.002;
                    peer.last_seq = Some(frame.seq);
                    peer.excess_ticks = 0;
                    // Push the samples below — don't return
                } else {
                    // In order
                    peer.last_seq = Some(frame.seq);
                }
            } else {
                // First packet from this peer
                peer.last_seq = Some(frame.seq);
            }
        }

        // ── Push audio ───────────────────────────────────────────────
        peer.samples.extend(frame.samples);

        // Hard cap: prevent runaway growth (e.g., frozen output, paused app).
        // This is a safety valve, not the normal drain path.
        let hard_cap = self.max_samples * 3;
        while peer.samples.len() > hard_cap {
            peer.samples.pop_front();
        }
    }

    /// Pull exactly `n` mixed samples, filling with silence if needed.
    ///
    /// Always mixes whatever audio is available for each peer (no hard gate).
    /// Normalization is based on peers that actually contribute meaningful
    /// audio energy to this frame, not just peers with non-empty buffers.
    /// This prevents quiet peers (DTX residue, silence) from reducing the
    /// volume of active speakers in large channels.
    pub fn pull_mixed(&mut self, n: usize, out: &mut [f32]) {
        debug_assert_eq!(out.len(), n);
        out.iter_mut().for_each(|s| *s = 0.0);

        let Ok(settings) = self.peer_settings.lock() else {
            return;
        };
        let mut contributing_peers = 0u32;

        // Temp buffer for per-peer limiting (reused across peers).
        // Allocated once on the stack for typical frame sizes.
        let mut peer_buf = vec![0.0f32; n];

        for (peer_id, peer) in self.buffers.iter_mut() {
            let peer_settings = settings.get(peer_id).cloned().unwrap_or_default();
            if peer_settings.is_muted {
                peer.samples.clear();
                continue;
            }

            if peer.samples.is_empty() {
                continue;
            }

            // Drain samples into temp buffer and apply volume
            let available = peer.samples.len().min(n);
            for slot in peer_buf[..available].iter_mut() {
                *slot = peer.samples.pop_front().unwrap_or(0.0) * peer_settings.volume;
            }
            peer_buf[available..n].fill(0.0);

            // Apply per-peer limiter (hearing protection)
            peer.limiter.process_samples(&mut peer_buf[..available]);

            // Sum into output mix and track energy
            let mut peer_energy = 0.0f32;
            for i in 0..available {
                out[i] += peer_buf[i];
                peer_energy += peer_buf[i] * peer_buf[i];
            }

            // Only count peers with meaningful audio (not silence/DTX residue).
            // Threshold: ~-60 dBFS per sample average.
            if available > 0 && (peer_energy / available as f32) > 1e-6 {
                contributing_peers += 1;
            }
        }

        // Soft-knee normalization: no scaling for 1-2 speakers,
        // gentle sqrt scaling above that. This keeps duets at full
        // volume while preventing clipping in large group conversations.
        if contributing_peers > 2 {
            let scale = 1.0 / ((contributing_peers as f32 - 1.0).sqrt());
            for s in out.iter_mut() {
                *s = (*s * scale).clamp(-0.99, 0.99);
            }
        }

        drop(settings); // release lock before drain

        // ── Burst-safe drain ────────────────────────────────────────
        // After a jitter spike, packets arrive in bursts and legitimately
        // fill the buffer well past target. The old code drained this
        // immediately, causing audible gaps right after recovery.
        //
        // New approach: only drain if excess has been sustained for 10+
        // consecutive ticks (100ms). This lets burst arrivals play out
        // naturally while still preventing unbounded growth from clock drift.
        let headroom = self.target_samples + (n * 4); // target + 4 frames

        for peer in self.buffers.values_mut() {
            if peer.samples.len() > headroom {
                peer.excess_ticks = peer.excess_ticks.saturating_add(1);

                if peer.excess_ticks > 10 {
                    // Sustained excess — this is clock drift, not a burst.
                    // Drain gently: remove half the excess per cycle to avoid
                    // a sudden jump in playout position.
                    let excess = peer.samples.len() - headroom;
                    let drain_amount = (excess / 2).max(1);
                    peer.samples.drain(..drain_amount);
                    // Don't reset excess_ticks — keep draining until stable
                }
            } else {
                peer.excess_ticks = 0;
            }
        }
    }

    /// Adapt target depth based on jitter estimates and buffer health.
    ///
    /// Called every 10ms by the output worker. Uses two signals:
    ///
    /// 1. **Jitter estimates** (from network arrival times) — tells us what
    ///    the network looks like right now.
    /// 2. **Health feedback** (late packets, gaps) — tells us if the current
    ///    target is actually too low.
    ///
    /// The target moves **up fast** on problems (scaled by severity) and
    /// **down slowly** during stable periods (over 200 ticks / 2s).
    pub fn adapt(&mut self) {
        if self.buffers.is_empty() {
            return;
        }

        // ── Compute jitter-based target ─────────────────────────────
        // Use 75th percentile across active peers instead of max.
        // This prevents one bad peer from inflating the buffer for everyone.
        let mut jitter_values: Vec<f32> = self
            .buffers
            .values()
            .filter(|p| p.last_arrival.is_some())
            .map(|p| p.jitter_estimate * 1000.0) // convert to ms
            .collect();

        let jitter_target_ms = if jitter_values.is_empty() {
            0.0
        } else {
            jitter_values.sort_by(|a, b| a.partial_cmp(b).unwrap_or(std::cmp::Ordering::Equal));
            let p75_idx = (jitter_values.len() * 3) / 4;
            let p75_jitter = jitter_values[p75_idx.min(jitter_values.len() - 1)];
            // Target = 2× p75 jitter — enough headroom without being excessive
            p75_jitter * 2.0
        };

        // ── Health-based adjustment ─────────────────────────────────
        let had_problems = self.late_count > 0 || self.gap_count > 0;

        if had_problems {
            // Problems detected — increase target, scaled by severity.
            // Gaps are weighted 2× because they indicate consecutive loss
            // (worse than a single late arrival).
            let severity = self.late_count as f32 + self.gap_count as f32 * 2.0;
            let bump_ms = (severity * 5.0).min(40.0); // 5ms per event, cap 40ms per cycle
            let current_ms = self.target_ms();
            let new_target_ms = (current_ms + bump_ms).min(self.max_ms());
            self.target_samples = self.ms_to_samples(new_target_ms);
            self.stable_ticks = 0;
        } else {
            // No problems — count stable ticks and slowly drain toward
            // the jitter-based target (which itself is slowly decreasing
            // via the asymmetric EMA).
            self.stable_ticks = self.stable_ticks.saturating_add(1);

            // After 200 stable ticks (~2s with no issues), start draining.
            // Drain rate: 0.2ms per tick = ~2ms/sec of target reduction.
            //
            // This is much more conservative than v0.5 (which drained 0.5ms/tick
            // after only 500ms of stability). On WiFi/cellular with periodic
            // jitter bursts every 1-3 seconds, v0.5's drain caused a
            // drain→spike→underrun→bump oscillation. 2s stability + 0.2ms/tick
            // breaks this cycle: the buffer only drains during genuinely stable
            // periods, and does so slowly enough that a single missed drain
            // cycle doesn't cause an underrun.
            if self.stable_ticks > 200 {
                let current_ms = self.target_ms();
                // Drain toward the jitter-based target, but never below min.
                let floor_ms = jitter_target_ms.max(self.min_ms());
                let new_target_ms = (current_ms - 0.2).max(floor_ms);
                self.target_samples = self.ms_to_samples(new_target_ms);
            }
        }

        // ── Always respect jitter-based minimum ─────────────────────
        // If jitter estimate says we need more than current target,
        // jump up immediately (don't wait for late packets to prove it).
        let jitter_samples = self.ms_to_samples(jitter_target_ms);
        if jitter_samples > self.target_samples {
            self.target_samples = jitter_samples;
        }

        // ── Clamp to [min, max] ─────────────────────────────────────
        self.target_samples = self
            .target_samples
            .clamp(self.min_samples, self.max_samples);

        // Reset event counters for next cycle
        self.late_count = 0;
        self.gap_count = 0;
    }

    pub fn occupancy_ms(&self) -> f32 {
        if self.buffers.is_empty() {
            return 0.0;
        }
        let avg: f32 = self
            .buffers
            .values()
            .map(|p| p.samples.len() as f32)
            .sum::<f32>()
            / self.buffers.len() as f32;
        (avg * 1000.0) / self.sample_rate as f32
    }

    /// Current target depth in milliseconds (for stats).
    pub fn target_ms(&self) -> f32 {
        (self.target_samples as f32 * 1000.0) / self.sample_rate as f32
    }

    // ── Internal helpers ────────────────────────────────────────────

    fn min_ms(&self) -> f32 {
        (self.min_samples as f32 * 1000.0) / self.sample_rate as f32
    }

    fn max_ms(&self) -> f32 {
        (self.max_samples as f32 * 1000.0) / self.sample_rate as f32
    }

    fn ms_to_samples(&self, ms: f32) -> usize {
        ((ms * self.sample_rate as f32) / 1000.0) as usize
    }
}
