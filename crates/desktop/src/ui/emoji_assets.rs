fn map() -> &'static HashMap<&'static str, &'static [u8]> {
    static MAP: OnceLock<HashMap<&'static str, &'static [u8]>> = OnceLock::new();
    MAP.get_or_init(|| TWEMOJI.iter().copied().collect())
}

/// PNG bytes for an exact emoji string, if bundled.
pub fn png(emoji: &str) -> Option<&'static [u8]> {
    map().get(emoji).copied()
}

/// All bundled emoji strings, longest first per leading char — the
/// matcher table for splitting message text into text/emoji runs.
pub fn by_first_char() -> &'static HashMap<char, Vec<&'static str>> {
    static IDX: OnceLock<HashMap<char, Vec<&'static str>>> = OnceLock::new();
    IDX.get_or_init(|| {
        let mut idx: HashMap<char, Vec<&'static str>> = HashMap::new();
        for (e, _) in TWEMOJI {
            if let Some(c) = e.chars().next() {
                idx.entry(c).or_default().push(e);
            }
        }
        for v in idx.values_mut() {
            v.sort_by_key(|e| std::cmp::Reverse(e.len()));
        }
        idx
    })
}

/// Decode a bundled emoji to an fltk RGBA image at `size`×`size` px.
/// Downscaled from the 72 px source with a triangle filter — crisp at
/// picker (24) and chat-line (17) sizes where font rendering is not.
pub fn rgb_image(emoji: &str, size: u32) -> Option<fltk::image::RgbImage> {
    let bytes = png(emoji)?;
    let decoded = ::image::load_from_memory_with_format(bytes, ::image::ImageFormat::Png)
        .ok()?
        .to_rgba8();
    let scaled = ::image::imageops::resize(
        &decoded,
        size.max(1),
        size.max(1),
        ::image::imageops::FilterType::Triangle,
    );
    fltk::image::RgbImage::new(
        scaled.as_raw(),
        size as i32,
        size as i32,
        fltk::enums::ColorDepth::Rgba8,
    )
    .ok()
}
